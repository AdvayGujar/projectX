import { writeFile } from "node:fs/promises";
import path from "node:path";
import {
  AlignmentType,
  Document,
  Footer,
  HeadingLevel,
  PageBreak,
  PageNumber,
  Packer,
  Paragraph,
  Table,
  TableCell,
  TableRow,
  TextRun,
  WidthType,
} from "docx";

import { assert, ensureOut, fileSize, outDir, readZip, zipText } from "./lib.mjs";

function paragraph(text, options = {}) {
  return new Paragraph({
    spacing: { after: 160 },
    ...options,
    children: [new TextRun({ text, size: 22, font: "Helvetica" })],
  });
}

function sectionHeading(text, level = HeadingLevel.HEADING_1) {
  return new Paragraph({
    heading: level,
    spacing: { before: 240, after: 120 },
    children: [new TextRun({ text, bold: true })],
  });
}

function bullet(text) {
  return new Paragraph({
    bullet: { level: 0 },
    spacing: { after: 80 },
    children: [new TextRun({ text, size: 22 })],
  });
}

function sampleTable() {
  const header = ["Check", "Target", "Result"];
  const rows = [
    ["PPTX", "12 slides", "pass"],
    ["XLSX", "1k rows", "pass"],
    ["DOCX", "headings + tables", "pass"],
  ];
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        children: header.map((text) => new TableCell({
          shading: { fill: "EDEAE4" },
          children: [new Paragraph({ children: [new TextRun({ text, bold: true })] })],
        })),
      }),
      ...rows.map((row) => new TableRow({
        children: row.map((text) => new TableCell({
          children: [new Paragraph({ children: [new TextRun({ text })] })],
        })),
      })),
    ],
  });
}

function buildDocument() {
  const children = [
    new Paragraph({
      heading: HeadingLevel.TITLE,
      children: [new TextRun({ text: "M0 Spike Report", bold: true, size: 44 })],
    }),
    paragraph("Generated by the docx library. If this opens in Word or Pages, the DOCX path is viable."),
  ];

  for (let index = 1; index <= 8; index += 1) {
    children.push(sectionHeading(`Section ${index}`));
    children.push(paragraph(`This is the body of section ${index}. It exists to verify that headings, spacing, and long text survive export.`));
    children.push(bullet("First supporting point"));
    children.push(bullet("Second supporting point"));
    if (index === 3) {
      children.push(sampleTable());
    }
    if (index < 8) {
      children.push(new Paragraph({ children: [new PageBreak()] }));
    }
  }

  return new Document({
    creator: "ProjectX",
    title: "M0 Spike Report",
    description: "DOCX feasibility check",
    sections: [{
      properties: { page: { margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 } } },
      footers: {
        default: new Footer({
          children: [new Paragraph({
            alignment: AlignmentType.CENTER,
            children: [
              new TextRun({ text: "ProjectX · " }),
              new TextRun({ children: [PageNumber.CURRENT] }),
            ],
          })],
        }),
      },
      children,
    }],
  });
}

export async function run() {
  await ensureOut();
  const file = path.join(outDir, "spike.docx");
  const buffer = await Packer.toBuffer(buildDocument());
  await writeFile(file, buffer);

  const zip = await readZip(file);
  const documentXml = await zipText(zip, "word/document.xml");
  const footers = Object.keys(zip.files).filter((name) => /^word\/footer\d+\.xml$/.test(name));
  const paragraphs = (documentXml.match(/<w:p[ >]/g) ?? []).length;
  const tables = (documentXml.match(/<w:tbl>/g) ?? []).length;

  assert(documentXml.includes("M0 Spike Report"), "document text missing");
  assert(paragraphs >= 20, `expected at least 20 paragraphs, got ${paragraphs}`);
  assert(tables === 1, `expected 1 table, got ${tables}`);
  assert(footers.length >= 1, "expected a footer part");

  return {
    name: "docx",
    ok: true,
    file,
    size: await fileSize(file),
    detail: `${paragraphs} paragraphs, ${tables} table, ${footers.length} footer`,
  };
}
